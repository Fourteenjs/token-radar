// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks every protocol the snapshot records as pre-token that is not a wrapped, staked or
// bridged product of a token that already trades, and not an exchange or a versioned pool. The
// watchlist is the floor: all 40 of its slugs are on the board, and the board adds every other
// rankable protocol below the floor, so the radar covers the early ones too.
//
// Implied value follows only from the snapshot's own figures, never from a hand-kept list of names:
//
//   multiple   = the median market-cap-to-TVL of the live-token protocols in the same category
//                (at least 3 of them, else the median across all live-token protocols),
//                clamped to [0.05, 2.0]
//   base       = tvl_usd x multiple
//   growth     = clamp(change_7d, -80, +200) per cent, null read as 0
//   growthMult = 1 + 0.5 x sign(growth) x ln(1 + |growth| / 100) / ln(3)
//                (a log dampener: +200% pays 1.50x, -80% pays 0.73x, 0% pays 1.00x)
//   maturity   = 0.6 + 0.4 x min(age_days, 1095) / 1095   (age unknown: 365 days)
//   implied    = max(1, round(base x growthMult x maturity))
//
// A protocol that has run longer with no token is worth more, because its launch, if it ever comes,
// has had longer to accumulate users; a protocol whose TVL is shrinking is worth less. The multiple
// is the market's own price for a dollar of TVL in that category, read off the protocols whose token
// already trades.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them and the sandbox may change them. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  growth_log_scale: number;
  growth_log_norm: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  min_live_per_category: number;
  multiple_floor: number;
  multiple_cap: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.5,
  growth_floor: -80,
  growth_cap: 200,
  growth_log_scale: 100,
  growth_log_norm: 3,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
  min_live_per_category: 3,
  multiple_floor: 0.05,
  multiple_cap: 2.0,
};

/** The model's version label: the dashboard names it and the rules quote it. */
export const MODEL_VERSION = 'radar-catmedian-1';

/** How many live-token protocols the Live token view carries, by market cap. */
export const LIVE_ROWS = 24;

/** A farm step: the action, what it costs, and how long it takes. */
export interface FarmStep {
  text: string;
  cost: string;
  time: string;
}

